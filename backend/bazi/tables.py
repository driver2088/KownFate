def shishen(day_gan, other_gan):
    """十神推导：日干为主，看他干（同字为比肩）。"""
    de, oe = STEM_ELEMENT[day_gan], STEM_ELEMENT[other_gan]
    same_polarity = (day_gan in STEM_YANG) == (other_gan in STEM_YANG)
    if oe == de:
        return "比肩" if same_polarity else "劫财"
    if GENERATES[de] == oe:          # 我生
        return "食神" if same_polarity else "伤官"
    if CONTROLLED[de] == oe:         # 我克
        return "偏财" if same_polarity else "正财"
    if CONTROLLED[oe] == de:         # 克我
        return "七杀" if same_polarity else "正官"
    if GENERATES[oe] == de:          # 生我
        return "偏印" if same_polarity else "正印"
    raise ValueError(f"{day_gan} {other_gan}")

